// ---------------------------------------------------------------- interface language

const STORAGE_KEY = "dalil.uiLang";
let lang = "en";

export function getLanguage() {
  return lang;
}

// Switch the interface language: sets <html lang dir> (Arabic and Urdu flip the whole
// page to right-to-left), remembers the choice in this browser, and tells the app.
export function setLanguage(code, { remember = true, silent = false } = {}) {
  const previous = lang;
  lang = STRINGS[code] ? code : "en";
  document.documentElement.lang = lang;
  document.documentElement.dir = RTL_LANGS.includes(lang) ? "rtl" : "ltr";
  if (remember) {
    try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* private browsing: still works, just not remembered */ }
  }
  if (lang !== previous && !silent) {
    window.dispatchEvent(new CustomEvent("dalil:language-changed", { detail: { lang, previous } }));
  }
  return lang;
}

// On load: the language picked last time in this browser; on a first visit, the phone's
// own language if Dalil has it ("fil" is the code phones use for Tagalog); else English.
export function initLanguage() {
  let saved = null;
  try { saved = localStorage.getItem(STORAGE_KEY); } catch { /* storage blocked */ }
  if (saved && STRINGS[saved]) return setLanguage(saved, { remember: false, silent: true });
  const phone = (navigator.languages || [navigator.language || ""])
    .map((l) => String(l).toLowerCase().split("-")[0])
    .map((l) => (l === "fil" ? "tl" : l))
    .find((l) => STRINGS[l]);
  return setLanguage(phone || "en", { remember: false, silent: true });
}

// t("h_cost") uses the interface language; t("h_cost", "ar") forces a language
// (the result card uses the answer language).
export function t(key, forLang = lang) {
  return (STRINGS[forLang] && STRINGS[forLang][key]) || STRINGS.en[key] || key;
}

// Re-fill every translatable element (used at start-up and whenever the language changes):
//   data-i18n="key"             -> the element's text
//   data-i18n-aria="key"        -> its aria-label (for icon buttons and screen readers)
//   data-i18n-placeholder="key" -> its placeholder
export function applyStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => el.setAttribute("aria-label", t(el.dataset.i18nAria)));
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder)));
}
