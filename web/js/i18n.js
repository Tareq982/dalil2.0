let lang = "en";

export function setLanguage(code) {
  lang = STRINGS[code] ? code : "en";
}

// t("h_cost") uses the interface language; t("h_cost", "ar") forces a language
// (the result card uses the answer language).
export function t(key, forLang = lang) {
  return (STRINGS[forLang] && STRINGS[forLang][key]) || STRINGS.en[key] || key;
}

// Fill every element that has data-i18n="key" (used by the static parts of index.html).
export function applyStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
}
